"""Splice a room's header rules into a Cloudflare Pages `_headers` file.

A site that is static HTML on Cloudflare Pages has no .htaccess and no
nginx: it reads one root `_headers` file for the whole site. The room's rules
therefore cannot be a file of their own on the host -- they have to go into the
site's one file, without disturbing anything else in it.

The build writes the fragment (`build.py _pages_headers`, `_headers.room`); this
puts it in place between two marker lines, and is a no-op the second time:

    python -m roomkit.pages_headers splice --headers _headers \\
        --fragment out/_headers.room --mount /documents/

The site is named by its pack (`identity.site`), which the build writes on the
fragment's first line, so the markers read `roomkit example /documents/`.
`--site` exists only to override that, and is refused when neither names one.

Two limits of the format are checked here rather than discovered on deploy:

- 100 header rules per file. Pages stops reading at the limit, so the room's
  rules would silently vanish past it.
- 2,000 characters per line, including indentation.

Anything outside the markers is left exactly as it was, because that file also
carries the archive's site-wide CSP, HSTS and noindex rules.

    python -m roomkit.pages_headers check --headers _headers

Exit codes: 0 ok, 1 the file has a problem, 2 usage.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

MAX_RULES = 100
MAX_LINE = 2000

# The build's first line: `# roomkit <site> <mount> -- ...` (build.py _pages_headers).
FRAGMENT = re.compile(r"^# roomkit (\S+) (\S+)")


def fragment_site(fragment: str) -> str:
    """The pack's site name, as the build wrote it on the fragment's first line."""
    match = FRAGMENT.match(fragment.split("\n", 1)[0])
    return match.group(1) if match else ""


def markers(site: str, mount: str) -> tuple[str, str]:
    """The two comment lines that fence the room's rules."""
    tag = f"roomkit {site} {mount}"
    return (
        f"# BEGIN {tag} -- generated by roomkit; edits between these lines are overwritten",
        f"# END {tag}",
    )


def splice(text: str, fragment: str, site: str, mount: str) -> str:
    """`text` with the room's rules between its markers, replacing any it had.

    Idempotent: splicing the same fragment twice returns the same text. A file
    without the markers gets them appended, so the site's own rules stay first
    and a human reading the file still sees them where they were.
    """
    begin, end = markers(site, mount)
    block = [begin, *fragment.rstrip("\n").split("\n"), end]

    lines = text.split("\n")
    if begin in lines:
        start = lines.index(begin)
        try:
            stop = lines.index(end, start)
        except ValueError:
            raise ValueError(f"{begin!r} has no matching {end!r}; refusing to guess where it ends") from None
        out = [*lines[:start], *block, *lines[stop + 1:]]
    else:
        body = text.rstrip("\n")
        out = [*body.split("\n"), "", *block, ""] if body else [*block, ""]
    return "\n".join(out)


def rules(text: str) -> list[str]:
    """The path patterns in a `_headers` file, in order.

    A rule line is flush left and is not a comment; its headers are indented
    under it. That is the whole grammar Pages documents.
    """
    return [
        line.strip() for line in text.split("\n")
        if line.strip() and not line.startswith(("#", " ", "\t"))
    ]


def check(text: str, site: str = "", mount: str = "") -> list[str]:
    """Everything wrong with this `_headers` file, as sentences. Empty is good."""
    problems: list[str] = []
    count = len(rules(text))
    if count > MAX_RULES:
        problems.append(
            f"{count} header rules, over Pages' limit of {MAX_RULES}: "
            "Pages stops reading at the limit, so the last rules never apply"
        )
    for n, line in enumerate(text.split("\n"), 1):
        if len(line) > MAX_LINE:
            problems.append(f"line {n} is {len(line)} characters, over Pages' limit of {MAX_LINE}")
    if site and mount:
        begin, end = markers(site, mount)
        lines = text.split("\n")
        has_begin, has_end = begin in lines, end in lines
        if has_begin != has_end:
            problems.append(
                f"the room's markers are unbalanced ({begin!r} present: {has_begin}, "
                f"{end!r} present: {has_end})"
            )
        elif has_begin and lines.index(end) < lines.index(begin):
            problems.append("the room's END marker comes before its BEGIN marker")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = parser.add_subparsers(dest="verb", required=True)

    sp = sub.add_parser("splice", help="put the fragment between its markers")
    sp.add_argument("--headers", required=True, help="the site's root _headers file")
    sp.add_argument("--fragment", required=True, help="the room's _headers.room")
    sp.add_argument("--site", default="", help="default: the pack's name, from the fragment's first line")
    sp.add_argument("--mount", required=True, help="the room's path, with slashes: /documents/")
    sp.add_argument("--check-only", action="store_true", help="report, write nothing")

    cp = sub.add_parser("check", help="a _headers file's rules, against Pages' limits")
    cp.add_argument("--headers", required=True)
    cp.add_argument("--site", default="")
    cp.add_argument("--mount", default="")

    args = parser.parse_args(argv)

    path = Path(args.headers)
    text = path.read_text(encoding="utf-8") if path.is_file() else ""

    if args.verb == "splice":
        fragment = Path(args.fragment).read_text(encoding="utf-8")
        site = args.site or fragment_site(fragment)
        if not site:
            print("REFUSED: the fragment does not name its pack; pass --site", file=sys.stderr)
            return 1
        try:
            out = splice(text, fragment, site, args.mount)
        except ValueError as exc:
            print(f"REFUSED: {exc}", file=sys.stderr)
            return 1
        problems = check(out, site, args.mount)
        if problems:
            for p in problems:
                print(f"[ERROR] {p}", file=sys.stderr)
            print("REFUSED: the spliced file would not be valid; nothing was written", file=sys.stderr)
            return 1
        if out == text:
            print(f"{path}: unchanged (the room's rules are already in place)")
            return 0
        if args.check_only:
            print(f"{path}: would change")
            return 0
        path.write_text(out, encoding="utf-8")
        print(f"{path}: spliced the room's rules ({len(rules(out))} rules in the file)")
        return 0

    problems = check(text, args.site, args.mount)
    for p in problems:
        print(f"[ERROR] {p}")
    if problems:
        return 1
    print(f"{path}: ok; {len(rules(text))} rules, under Pages' limit of {MAX_RULES}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
